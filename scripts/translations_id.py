# Strings that are the same in every language.
UNTRANSLATED = {"", " ", "%", "%@ %@", "%lld", "%lld · %@", "%lld%%", "10 GB", "20 GB", "5 GB", "50 GB", "…",
                "Bahasa Indonesia", "English", "Macintosh HD", "Novra", "naqara.dev",
                "Powered by naqara.dev · © 2026 Naqara Dev", "Mail", "Space Lens", "GitHub"}


def main():
    catalog = json.loads(CATALOG.read_text())
    strings = catalog["strings"]
    for key in ID:
        strings.setdefault(key, {})
    missing = []
    for key, entry in strings.items():
        if key in UNTRANSLATED:
            entry["shouldTranslate"] = False
            continue
        if key not in ID:
            missing.append(key)
            continue
        entry.setdefault("localizations", {})["id"] = {"stringUnit": {"state": "translated", "value": ID[key]}}
    CATALOG.write_text(json.dumps(catalog, ensure_ascii=False, indent=2, sort_keys=True) + "\n")
    print(f"{len(ID)} translations written.")
    if missing:
        print("Still in English:", *missing, sep="\n  ")


if __name__ == "__main__":
    main()
